// `operator` стоит ВНУТРИ ТИПА, а не в имени. Это законное СКАЛЯРНОЕ поле —
// указатель на член-функцию, то есть ровно тот неинициализированный скаляр, ради
// которого гард существует. Прежний фильтр грепал `\boperator\b` по всему
// объявлению и списывал такое поле в «методы»: 0 полей, 0 неинициализированных,
// 0 неразобранных — молчание. Теперь объявление не доказано оператором, идёт по
// обычному пути и ГРОМКО останавливает гард (форму `decltype(...) имя` разбор не
// умеет отнести ни к методу, ни к полю).
// Ожидание: код 2, полей 0, методов 0, неразобранных 1.
